/*
Operadores Relacionais em JS

== -> igual
=== -> estritamente igual valor e tipo
!== -> estritamente diferente valor e tipo
!= -> diferente
> -> maior que
< -> menor que
>= -> maior ou igual
<= -> menor ou igual
*/

// Exemplos

let num1 = 7
let num2 = "7"
let num3 = 3

console.log(num1 == num2) // Verifica apenas valor 
console.log(num1 === num2) // Verifica valor e tipo
console.log(num1 != num2) // Verifica apenas valor
console.log(num1 !== num2) // Verifica apenas valor
console.log(num1 > num3) // Verifica se o valor é maior
console.log(num1 < num2) // Verifica se o valor é maior
console.log(num1 >= num3) // Verifica se o valor é maior ou igual
console.log(num1 <= num3) // Verifica se o valor é menor pu igual